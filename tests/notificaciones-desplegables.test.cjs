const assert = require('node:assert/strict');
const {boot}=require('./boot.cjs');
const dom=boot(), run=code=>dom.window.run(code);
run(`S.mode='home';S.orders=[{id:'order1',order_no:1,title:'Pedido ficticio',kind:'customer',
 status:'printing',due_date:localToday(),quantity:1,unit_price:1000}];render();`);
assert.equal(run(`q('.notification-badge').textContent`),'1');
run(`q('[data-notifications]').click()`);
assert.equal(run(`q('#notificationsMenu').open`),true);
assert.equal(run(`q('dialog')`),null);
assert.equal(run(`q('.notification-badge')`),null);
assert.equal(run(`q('[data-notifications]').getAttribute('aria-expanded')`),'true');
assert.equal(run(`reminders().length`),1,'Reading does not clear operational reminders');
run(`q('#accountMenu summary').click()`);
assert.equal(run(`q('#notificationsMenu').open`),false);
assert.equal(run(`q('#accountMenu').open`),true);
run(`q('#accountMenu').dispatchEvent(new KeyboardEvent('keydown',{key:'Escape',bubbles:true}))`);
assert.equal(run(`q('#accountMenu').open`),false);
assert.equal(run(`document.activeElement`),run(`q('#accountMenu summary')`));
run('render()');
assert.equal(run(`q('.notification-badge')`),null,'Seen state survives re-render');
run(`S.orders[0].due_date='2000-01-01';render()`);
assert.equal(run(`q('.notification-badge').textContent`),'1','Changed alert becomes new');
run(`S.workspace.id='other';render()`);
assert.equal(run(`q('.notification-badge').textContent`),'1','Seen preference is workspace scoped');
run(`S.workspace.id='workspace';S.orders=[];render()`);
assert.equal(run(`q('.notification-badge')`),null,'No fabricated count when empty');
run(`q('#accountMenu summary').click();document.body.click()`);
assert.equal(run(`q('#accountMenu').open`),false);
run(`q('#accountButton').click()`);
assert.equal(run(`S.mode`),'profile');
assert.equal(run(`q('[data-header-profile]')`),null,'No duplicate avatar in header');
console.log('PASS desplegables: vistos por dispositivo/espacio, alertas nuevas, foco, Escape, exterior y perfil único');
